/**
 * Miguel, 2026-10-21: starters and rice/legume dishes no longer need 80 g of
 * meat, fish or egg per serving — except in a household whose ficha says
 * someone wants protein in every dish (fact `protein_minimum`, today only
 * him). The menu loader reads the household ficha and passes it to the
 * catalogue audit.
 */
import { describe, expect, it, vi } from 'vitest'

vi.mock('../services/recipeVisibility.js', () => ({
  visibleAuthorIds: async (userId: string) => [userId],
  visibleRecipeWhere: () => undefined,
}))

const { loadMatchableRecipes } = await import('../services/matchableRecipes.js')

/** Drizzle-like chain whose awaited queries return `responses` in order. */
function makeDb(...responses: any[]) {
  const queue = [...responses]
  const node: any = new Proxy(
    {},
    {
      get(_, prop) {
        if (prop === 'then') {
          return (resolve: any, reject?: any) =>
            queue.length === 0 ? Promise.reject(new Error('mockDb: queue empty')) : Promise.resolve(queue.shift()).then(resolve, reject)
        }
        return () => node
      },
    },
  )
  return node
}

const garbanzos = { id: 'r-g', name: 'Garbanzos con espinacas y huevo', authorId: null, servings: 4, course: 'main', meals: ['lunch', 'dinner'], seasons: [] }
const lines = [
  { recipeId: 'r-g', ingredientId: 'i1', quantity: 667, unit: 'g', ingredientName: 'garbanzos cocidos', allergenTags: [], containsTags: [], unitWeight: null, density: null, edibleFraction: 1 },
  { recipeId: 'r-g', ingredientId: 'i2', quantity: 6, unit: 'u', ingredientName: 'huevo', allergenTags: ['huevo'], containsTags: [], unitWeight: 50, density: null, edibleFraction: 1 },
  { recipeId: 'r-g', ingredientId: 'i3', quantity: 133, unit: 'g', ingredientName: 'espinacas', allergenTags: [], containsTags: [], unitWeight: null, density: null, edibleFraction: 1 },
]
const steps = [1, 2, 3, 4, 5, 6].map((index) => ({ recipeId: 'r-g', index, text: `Paso ${index}` }))

const fact = (over: Record<string, unknown> = {}) => ({
  id: 'f1', householdId: 'h1', subjectUserId: 'u-miguel', subjectPersonId: null, type: 'protein_minimum',
  value: { scope: 'every_dish' }, origin: 'user', confidence: 1, validUntil: null, sourceMemoryId: null, status: 'active', ...over,
})
/** The ficha reads: the user's household, its active facts, its persons, its portrait. */
const ficha = (facts: unknown[]) => [[{ householdId: 'h1' }], facts, [], []]

describe('loadMatchableRecipes — the household ficha decides the protein minimum', () => {
  it('for everyone, garbanzos with 75 g of egg per serving can go in the menu', async () => {
    const [r] = await loadMatchableRecipes('u-1', makeDb([garbanzos], ...ficha([]), lines, steps))
    expect(r.catalogAuditIssues).toEqual([])
  })

  it('a household where someone wants protein in every dish does not get it', async () => {
    const [r] = await loadMatchableRecipes('u-miguel', makeDb([garbanzos], ...ficha([fact()]), lines, steps))
    expect(r.catalogAuditIssues).toEqual(['proteina_fuera_de_rango'])
    // …also when the menu is generated by another member of the household
    const [other] = await loadMatchableRecipes('u-partner', makeDb([garbanzos], ...ficha([fact()]), lines, steps))
    expect(other.catalogAuditIssues).toEqual(['proteina_fuera_de_rango'])
  })

  it('a retired or expired fact no longer counts', async () => {
    const [retired] = await loadMatchableRecipes('u-miguel', makeDb([garbanzos], ...ficha([fact({ status: 'retired' })]), lines, steps))
    expect(retired.catalogAuditIssues).toEqual([])
    const [expired] = await loadMatchableRecipes('u-miguel', makeDb([garbanzos], ...ficha([fact({ validUntil: new Date('2026-01-01') })]), lines, steps))
    expect(expired.catalogAuditIssues).toEqual([])
  })

  it('no household (or the ficha fails to load) means the default', async () => {
    const [r] = await loadMatchableRecipes('u-x', makeDb([garbanzos], [], lines, steps))
    expect(r.catalogAuditIssues).toEqual([])
  })
})
