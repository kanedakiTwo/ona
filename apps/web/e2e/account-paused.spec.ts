/**
 * PRO-385 (D-158, specs/billing.md): a trial that ended without a plan is on
 * Gratis «lo haces tú», at 390×844. It generates its week, sees «Estás en el
 * plan Gratis», and Mimo's panel says Mimo rests, with «Elegir plan». Gratis
 * only exists from launch day (2026-12-15), so the real API says `beta`
 * today: the spec answers `GET /billing` as the API does after the trial (the
 * rule and the API guards are tested in apps/api/src/tests/planGratis.test.ts).
 */

import { test, expect, type Page } from '@playwright/test'
import { completeOnboarding, registerFreshUser } from './_helpers'
import { madridMondayIn } from './_clock'

type Access = {
  state: 'beta' | 'trial' | 'gratis' | 'subscribed'
  trialDays?: number
  trialEndsAt: string
  trialLastDay: string
  daysLeft: number | null
}

async function billingAs(page: Page, access: Access) {
  await page.route(/\/billing$/, (route) =>
    route.request().method() === 'GET'
      ? route.fulfill({
          json: {
            enabled: true,
            beta: false,
            launchDate: '2026-12-15',
            canManage: true,
            firstChargeAt: '2027-02-16T11:00:00.000Z',
            access,
            subscription: null,
          },
        })
      : route.continue(),
  )
}

const GRATIS: Access = { state: 'gratis', trialEndsAt: '2027-01-24T23:00:00.000Z', trialLastDay: '2027-01-24', daysLeft: null }

test('trial over: «Estás en el plan Gratis» on /menu, Mimo rests, «Elegir plan» opens the plans', async ({ page }) => {
  test.setTimeout(90_000)
  await page.setViewportSize({ width: 390, height: 844 })
  await registerFreshUser(page)
  if (page.url().includes('/onboarding')) await completeOnboarding(page)

  await billingAs(page, GRATIS)
  await page.goto('/menu')
  const card = page.getByTestId('plan-gratis').first()
  await expect(card).toBeVisible({ timeout: 15_000 })
  await expect(card).toContainText('Estás en el plan Gratis')
  await expect(card).toContainText('no se borra nada')

  // Mimo: no composer, «Mimo descansa» and the plans.
  await page.getByTestId('mimo-button').click()
  await expect(page.getByTestId('mimo-input')).toHaveCount(0)
  const panel = page.getByTestId('mimo-panel').getByTestId('plan-gratis')
  await expect(panel).toContainText('En el plan Gratis, Mimo descansa. Con Esencial vuelve a haceros la semana él solo.')
  await expect(panel.getByTestId('plan-gratis-cta')).toHaveText('Elegir plan')
  await page.keyboard.press('Escape')

  await card.getByTestId('plan-gratis-cta').click()
  await expect(page).toHaveURL(/\/profile\/suscripcion/)
  await expect(page.getByTestId('subscription-gratis')).toContainText('Estás en el plan Gratis')
  // Choosing a plan: the paid plans and the pay button.
  await expect(page.getByTestId('subscribe-cta')).toHaveText(/Suscribirme a Esencial · pago el 16 de febrero/)
})

test('trial over: the account still generates its week from the web', async ({ page }) => {
  // Same flow as week-plan-questions.spec.ts («skipping the questions generates the week»).
  test.setTimeout(90_000)
  await registerFreshUser(page)
  await completeOnboarding(page)
  await billingAs(page, GRATIS)
  // Two weeks ahead: never generated by the sign-up, so it's blank.
  await page.goto(`/menu?week=${madridMondayIn(2)}`)
  await expect(page.getByRole('button', { name: 'Generar mi menú' })).toBeVisible({ timeout: 20_000 })
  await expect(page.getByTestId('plan-gratis').first()).toBeVisible()

  await Promise.all([
    page.waitForRequest((r) => r.url().endsWith('/menu/generate') && r.method() === 'POST' && !r.postDataJSON()?.empty),
    page.getByRole('button', { name: 'Generar mi menú' }).click(),
  ])
  // Generated: the blank-week button is gone (a 402 would leave it there).
  await expect(page.getByRole('button', { name: 'Generar mi menú' })).toHaveCount(0, { timeout: 30_000 })
})

test('two days left: /menu warns once, with the last day and what Gratis keeps', async ({ page }) => {
  test.setTimeout(90_000)
  await page.setViewportSize({ width: 390, height: 844 })
  await registerFreshUser(page)
  if (page.url().includes('/onboarding')) await completeOnboarding(page)

  await billingAs(page, { state: 'trial', trialEndsAt: '2027-01-24T23:00:00.000Z', trialLastDay: '2027-01-24', daysLeft: 2 })
  await page.goto('/menu')
  const notice = page.getByTestId('trial-ending')
  await expect(notice).toBeVisible({ timeout: 15_000 })
  await expect(notice).toContainText('Te quedan 2 días de prueba')
  await expect(notice).toContainText('hasta el 24 de enero')
  await expect(notice).toContainText('pasas al plan Gratis')
  await expect(page.getByTestId('plan-gratis')).toHaveCount(0)
})

